BEGIN;

-- 1. Libraries (one row per library that buys the software)
CREATE TABLE IF NOT EXISTS libraries (
    library_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(80) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO libraries (library_id, name, slug)
VALUES (1, 'Default Library', 'default-library')
ON CONFLICT (library_id) DO NOTHING;

SELECT setval(pg_get_serial_sequence('libraries', 'library_id'), (SELECT MAX(library_id) FROM libraries));

-- 2. library_id on every tenant table
ALTER TABLE users ADD COLUMN IF NOT EXISTS library_id BIGINT;
ALTER TABLE categories ADD COLUMN IF NOT EXISTS library_id BIGINT;
ALTER TABLE books ADD COLUMN IF NOT EXISTS library_id BIGINT;
ALTER TABLE issues ADD COLUMN IF NOT EXISTS library_id BIGINT;
ALTER TABLE returns ADD COLUMN IF NOT EXISTS library_id BIGINT;
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS library_id BIGINT;

UPDATE users SET library_id = 1 WHERE library_id IS NULL;
UPDATE categories SET library_id = 1 WHERE library_id IS NULL;
UPDATE books SET library_id = 1 WHERE library_id IS NULL;
UPDATE issues SET library_id = 1 WHERE library_id IS NULL;
UPDATE returns SET library_id = 1 WHERE library_id IS NULL;
UPDATE reservations SET library_id = 1 WHERE library_id IS NULL;

ALTER TABLE users ALTER COLUMN library_id SET NOT NULL;
ALTER TABLE categories ALTER COLUMN library_id SET NOT NULL;
ALTER TABLE books ALTER COLUMN library_id SET NOT NULL;
ALTER TABLE issues ALTER COLUMN library_id SET NOT NULL;
ALTER TABLE returns ALTER COLUMN library_id SET NOT NULL;
ALTER TABLE reservations ALTER COLUMN library_id SET NOT NULL;

DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['users', 'categories', 'books', 'issues', 'returns', 'reservations']
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = t || '_library_fk') THEN
            EXECUTE format(
                'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (library_id) REFERENCES libraries (library_id)',
                t, t || '_library_fk'
            );
        END IF;
    END LOOP;
END $$;

-- ISBN is unique per library, not across all libraries
ALTER TABLE books DROP CONSTRAINT IF EXISTS books_isbn_key;
CREATE UNIQUE INDEX IF NOT EXISTS uq_books_library_isbn ON books (library_id, isbn);

CREATE INDEX IF NOT EXISTS idx_users_library ON users (library_id);
CREATE INDEX IF NOT EXISTS idx_categories_library ON categories (library_id);
CREATE INDEX IF NOT EXISTS idx_books_library ON books (library_id);
CREATE INDEX IF NOT EXISTS idx_issues_library ON issues (library_id);
CREATE INDEX IF NOT EXISTS idx_returns_library ON returns (library_id);
CREATE INDEX IF NOT EXISTS idx_reservations_library ON reservations (library_id);

-- 3. Accounts: password, verification, lockout, Google link, new roles
-- Remove the old role rule FIRST, so the role change below is allowed.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;

UPDATE users SET role = 'member' WHERE role = 'patron';
UPDATE users SET role = 'owner' WHERE user_id = 1;

ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('owner', 'librarian', 'member'));

ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
UPDATE users SET password_hash = NULL
WHERE password_hash LIKE 'hash_demo%' OR password_hash = 'temp_hash_demo';

ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS failed_login_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS locked_until TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_sub VARCHAR(255) UNIQUE;

-- Existing seed accounts are treated as verified; they set a password via "Forgot password".
UPDATE users SET email_verified_at = CURRENT_TIMESTAMP WHERE email_verified_at IS NULL;

-- 4. Login sessions (server-side, so you can log out a device or all devices)
CREATE TABLE IF NOT EXISTS sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    user_agent TEXT,
    ip_address VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);

-- 5. One-time tokens for email verification and password reset
CREATE TABLE IF NOT EXISTS auth_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    purpose VARCHAR(30) NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Fine rules (owner-only, one row per library)
CREATE TABLE IF NOT EXISTS fine_rules (
    library_id BIGINT PRIMARY KEY REFERENCES libraries (library_id),
    per_day_amount NUMERIC(10,2) NOT NULL DEFAULT 0.50 CHECK (per_day_amount >= 0),
    grace_days INTEGER NOT NULL DEFAULT 0 CHECK (grace_days >= 0),
    max_amount NUMERIC(10,2) NOT NULL DEFAULT 20.00 CHECK (max_amount >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT REFERENCES users (user_id)
);

INSERT INTO fine_rules (library_id) VALUES (1)
ON CONFLICT (library_id) DO NOTHING;

-- 7. Fines (one row per loan, amount written only by the system)
CREATE TABLE IF NOT EXISTS fines (
    fine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id BIGINT NOT NULL REFERENCES libraries (library_id),
    issue_id BIGINT NOT NULL UNIQUE REFERENCES issues (issue_id),
    user_id BIGINT NOT NULL REFERENCES users (user_id),
    days_charged INTEGER NOT NULL DEFAULT 0 CHECK (days_charged >= 0),
    amount NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid')),
    paid_at TIMESTAMPTZ,
    paid_by BIGINT REFERENCES users (user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_fines_library_status ON fines (library_id, status);
CREATE INDEX IF NOT EXISTS idx_fines_user ON fines (user_id);

-- 8. Audit log (append-only: updates and deletes are blocked by a trigger)
CREATE TABLE IF NOT EXISTS audit_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id BIGINT REFERENCES libraries (library_id),
    actor_user_id BIGINT REFERENCES users (user_id),
    action VARCHAR(60) NOT NULL,
    entity VARCHAR(40),
    entity_id TEXT,
    details JSONB,
    ip_address VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_library_time ON audit_log (library_id, created_at);

CREATE OR REPLACE FUNCTION forbid_audit_changes()
RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS audit_log_no_change ON audit_log;
CREATE TRIGGER audit_log_no_change
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION forbid_audit_changes();

-- 9. Record this migration
CREATE TABLE IF NOT EXISTS schema_migrations (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO schema_migrations (version) VALUES ('002_multi_library_auth')
ON CONFLICT (version) DO NOTHING;

COMMIT;

